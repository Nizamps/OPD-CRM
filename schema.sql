create extension if not exists pgcrypto;

do $$ begin create type public.app_role as enum ('admin','caller'); exception when duplicate_object then null; end $$;
do $$ begin create type public.campaign_status as enum ('draft','active','completed'); exception when duplicate_object then null; end $$;
do $$ begin create type public.calling_status as enum ('not_called','connected','dnp','busy','switched_off','wrong_number','interested','not_interested','follow_up','opd_booked','call_back'); exception when duplicate_object then null; end $$;
do $$ begin create type public.opd_status as enum ('not_discussed','interested','opd_recommended','opd_booked','opd_completed','no_show','cancelled'); exception when duplicate_object then null; end $$;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text not null,
  role public.app_role not null default 'caller',
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);
create table if not exists public.lead_sources (
  id uuid primary key default gen_random_uuid(), name text unique not null,
  is_active boolean not null default true, created_at timestamptz not null default now()
);
create table if not exists public.campaigns (
  id uuid primary key default gen_random_uuid(), name text not null, campaign_date date not null,
  status public.campaign_status not null default 'draft', location text, notes text,
  created_by uuid references public.profiles(id), created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);
create table if not exists public.leads (
  id uuid primary key default gen_random_uuid(), lead_number bigint generated by default as identity unique,
  patient_name text not null, phone text not null, alternate_phone text, source_id uuid not null references public.lead_sources(id),
  campaign_id uuid not null references public.campaigns(id), assigned_to uuid references public.profiles(id),
  calling_status public.calling_status not null default 'not_called', opd_status public.opd_status not null default 'not_discussed',
  follow_up_date date, follow_up_time time, remarks text, created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);
create table if not exists public.call_logs (
  id uuid primary key default gen_random_uuid(), lead_id uuid not null references public.leads(id) on delete cascade,
  caller_id uuid not null references public.profiles(id), calling_status public.calling_status not null, remarks text,
  called_at timestamptz not null default now()
);
create table if not exists public.follow_ups (
  id uuid primary key default gen_random_uuid(), lead_id uuid not null references public.leads(id) on delete cascade,
  assigned_to uuid references public.profiles(id), follow_up_date date not null, follow_up_time time,
  status text not null default 'open', notes text, created_at timestamptz not null default now(), completed_at timestamptz
);
create table if not exists public.opd_bookings (
  id uuid primary key default gen_random_uuid(), lead_id uuid not null references public.leads(id) on delete cascade,
  booking_date date, doctor_name text, department text, hospital_name text, booking_status text not null default 'booked',
  notes text, created_by uuid references public.profiles(id), created_at timestamptz not null default now()
);
create table if not exists public.lead_assignments (
  id uuid primary key default gen_random_uuid(), lead_id uuid not null references public.leads(id) on delete cascade,
  assigned_to uuid not null references public.profiles(id), assigned_by uuid references public.profiles(id), assigned_at timestamptz not null default now()
);
create table if not exists public.import_batches (
  id uuid primary key default gen_random_uuid(), source_id uuid references public.lead_sources(id), campaign_id uuid references public.campaigns(id),
  imported_by uuid references public.profiles(id), file_name text, row_count int default 0, inserted_count int default 0,
  duplicate_count int default 0, created_at timestamptz not null default now()
);
create table if not exists public.activity_logs (
  id uuid primary key default gen_random_uuid(), user_id uuid references public.profiles(id), action text not null,
  entity_type text, entity_id uuid, metadata jsonb, created_at timestamptz not null default now()
);
create index if not exists leads_phone_idx on public.leads(phone);
create index if not exists leads_campaign_idx on public.leads(campaign_id);
create index if not exists leads_assigned_idx on public.leads(assigned_to);
create index if not exists leads_status_idx on public.leads(calling_status);

